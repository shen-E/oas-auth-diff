// Regenerate the finite evaluator oracle with the ECMAScript RegExp engine.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const alphabet = ["a", "b", "0", "-", "\n", "é", "🚀", "猫", "\u00a0"];
const words = [""];
let frontier = [""];
for (let depth = 0; depth < 3; depth++) {
  frontier = frontier.flatMap(prefix => alphabet.map(char => prefix + char));
  words.push(...frontier);
}
const extraCodePoints = [9, 11, 12, 13, 32, 0x85, 0x1680, 0x180e, 0x2000, 0x200a,
  0x200b, 0x2028, 0x2029, 0x202f, 0x205f, 0x3000, 0xfeff, 0xe000, 0xffff];
for (const code of extraCodePoints) {
  const word = String.fromCodePoint(code);
  if (!words.includes(word)) words.push(word);
}
const patterns = ["", "a", "^a", "a$", "^a$", "^a|b$", "^$", "$^", "[]", "a|", "(?:)",
  "[ab]", "^[ab]+$", "^[a-b]{0,2}$", "^[a-]+$", "[-a]", "[[]", "^a{0}$", "^a{2,}$",
  "^(a|ab)*$", "^(a?)*$", "^(ab|b)+$", "^a??b?$", "a+b*", "^\\d\\w?$", "\\n$",
  "^\\x61\\u0062$", "^\\t?$", "^a$|^b$", "^((a|b)?)*$", "[0-9_]", "^a{1,3}?$",
  "^\\^$", "a\\$", "^[\\d-]+$", "[\\b]", "a^b", "a$b",
  "猫", "^猫+$", "^[一-龥é]{1,2}$", "^\\u732b\\xE9$", "\\s", "^\\s$", "^\\s+$",
  "^[\\s猫]+$", "^\\uFEFF$", "^é?$", "^[\\u0000-\\u007F]+$", "^[\\uE000-\\uFFFF]$"];
const cases = patterns.map(pattern => {
  const regex = new RegExp(pattern, "u");
  const bits = words.map(word => regex.test(word) ? "1" : "0").join("");
  const legacy = new RegExp(pattern);
  if (words.some((word, index) => legacy.test(word) !== (bits[index] === "1"))) {
    throw new Error("Code-unit/Unicode disagreement for supported pattern: " + pattern);
  }
  return `    (${JSON.stringify(pattern)}, ${JSON.stringify(bits)}),`;
});
const source = `// Generated by node schema/pattern_reference.mjs using ECMAScript RegExp.
///|
test "pattern evaluation agrees with the ECMAScript finite-word oracle" {
  let alphabet = ${JSON.stringify(alphabet)}
  let words = [""]
  let mut frontier = [""]
  for _ in 0..<3 {
    let next = []
    for prefix in frontier {
      for char in alphabet { next.push(prefix + char) }
    }
    words.append(next)
    frontier = next
  }
  let extras : Array[Int] = ${JSON.stringify(extraCodePoints)}
  for code in extras {
    let word = code.to_char().unwrap().to_string()
    if !words.contains(word) { words.push(word) }
  }
  let cases : Array[(String, String)] = [
${cases.join("\n")}
  ]
  for (pattern, bits) in cases {
    let schema = @schema.parse({ "type": "string", "pattern": pattern })
    assert_eq(bits.length(), words.length())
    for index, word in words {
      assert_eq(schema.accepts(Json::string(word)), bits[index] == '1')
    }
  }
}
`;
writeFileSync(fileURLToPath(new URL("pattern_oracle_test.mbt", import.meta.url)), source);
console.log(`ECMAScript pattern oracle: ${patterns.length} patterns × ${words.length} words`);
